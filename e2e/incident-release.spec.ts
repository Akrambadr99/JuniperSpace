import { expect, test } from '@playwright/test';
test('current incident custody controls regulatory approval and dispatch without rewriting old reviews', async ({ page }) => {
  await page.goto('/operations');
  const action = async (name: string) => page.getByRole('button', { name, exact: true }).click();
  const save = async () => { await action('Save command'); await expect(page.getByRole('dialog')).toHaveCount(0); };
  await page.getByRole('combobox', { name: 'Current actor' }).selectOption('actor-2');
  await page.getByRole('button', { name: /^Evidence items/ }).click();
  await action('Record evidence analysis'); await save(); await action('Seal evidence custody'); await save();
  await page.goto('/breach-notification');
  await page.getByText('Authoritative incident evidence', { exact: true }).click();
  await page.getByRole('combobox', { name: 'Source incident', exact: true }).selectOption('incident-1');
  await page.getByRole('combobox', { name: 'Source incident evidence', exact: true }).selectOption('evidence-1');
  await page.getByLabel('Incident association reason').fill('This acquired image supports the selected regulatory investigation.');
  await action('Prepare case release evidence');
  const history = page.getByRole('list', { name: 'Case preparation history' });
  await expect(history).toContainText('custodian actor-2');
  const role = page.getByRole('combobox', { name: 'Response control role', exact: true });
  await role.selectOption('Compliance Lead'); await action('Reassign urgent legal review'); await action('Approve case release evidence');
  await page.goto('/operations');
  await page.getByRole('combobox', { name: 'Current actor' }).selectOption('actor-2');
  await page.getByRole('button', { name: /^Evidence items/ }).click();
  await action('Request custody transfer');
  await page.getByRole('dialog').getByLabel('Transfer reason', { exact: true }).fill('Transfer for independent regulatory evidence review.'); await save();
  await page.getByRole('combobox', { name: 'Current actor' }).selectOption('actor-0');
  await page.getByRole('button', { name: /^Custody transfers/ }).click(); await action('Accept custody transfer');
  await page.getByRole('dialog').getByLabel('Acknowledgement note', { exact: true }).fill('Received sealed evidence with its original digest intact.'); await save();
  await page.goto('/breach-notification'); await role.selectOption('Compliance Lead'); await action('Dispatch approved response');
  await expect(page.getByRole('status')).toContainText('custody changed');
  await expect(page.getByRole('list', { name: 'Response dispatch history' }).locator('li')).toHaveCount(0);
  await page.getByText('Authoritative incident evidence', { exact: true }).click(); await action('Refresh incident sources');
  await expect(page.getByRole('combobox', { name: 'Source incident evidence', exact: true })).toHaveValue('evidence-1');
  await expect(page.getByLabel('Incident association reason')).toHaveValue('This acquired image supports the selected regulatory investigation.');
  await role.selectOption('Compliance Analyst'); await action('Prepare case release evidence');
  await expect(history.locator('li')).toHaveCount(2); await expect(history).toContainText('custodian actor-2'); await expect(history).toContainText('custodian actor-0');
  await role.selectOption('Compliance Lead'); await action('Approve case release evidence'); await action('Dispatch approved response'); await action('Acknowledge and close response');
  await expect(page.getByRole('status')).toContainText('closed after independent approval');
  await page.reload(); await expect(history.locator('li')).toHaveCount(2);
});
